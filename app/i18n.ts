export function localizeText(locale: Locale, value: string) {
  if (locale === "ko" || !value) return value;
  const exact = exactEnglish[value];
  if (exact) return exact;

  let localized = value;
  for (const [pattern, replacement] of englishPatterns) {
    if (pattern.test(localized)) {
      localized = localized.replace(pattern, replacement);
      break;
    }
  }

  return Object.entries(exactEnglish)
    .filter(([korean]) => korean.length >= 2)
    .sort(([left], [right]) => right.length - left.length)
    .reduce(
      (text, [korean, english]) => text.replaceAll(korean, english),
      localized,
    );
}
